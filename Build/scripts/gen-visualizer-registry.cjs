const fs = require("fs");
const path = require("path");

const visualizersDir = path.resolve(
  __dirname,
  "..",
  "src",
  "ui",
  "resources",
  "visualizers",
);
const outFile = path.join(visualizersDir, "_registry.ts");

const entries = fs
  .readdirSync(visualizersDir)
  .filter((name) => /\.visualizer\.tsx$/.test(name))
  .sort();

if (entries.length === 0) {
  console.error("no visualizer files found");
  process.exit(1);
}

const NAME_PATTERN = /^\s*name:\s*"([^"]*)"/m;

const displayNames = new Map();
for (const name of entries) {
  const source = fs.readFileSync(path.join(visualizersDir, name), "utf8");
  const match = NAME_PATTERN.exec(source);
  if (!match) {
    console.error(`no display name found in ${name}`);
    process.exit(1);
  }
  displayNames.set(name.replace(/\.visualizer\.tsx$/, ""), match[1]);
}

const lines = [
  "/* GENERATED by scripts/gen-visualizer-registry.cjs - do not edit by hand. */",
  "/* Regenerate with: npm run generate:visualizers */",
  'import type { VisualizerType } from "../../../platform/visualizers/visualizerLoader";',
  "",
  "const visualizerModules = {",
];

for (const name of entries) {
  const moduleName = name.replace(/\.visualizer\.tsx$/, "");
  const key = `../visualizers/${moduleName}.visualizer.tsx`;
  lines.push(
    `  [${JSON.stringify(key)}]: () =>`,
    `    import(${JSON.stringify(`./${moduleName}.visualizer`)}).then((m) => m.default as VisualizerType),`,
  );
}

lines.push(
  "} as Record<string, () => Promise<VisualizerType>>;",
  "",
  "const visualizerDisplayNames: Record<string, string> = {",
);
for (const [key, label] of displayNames) {
  lines.push(`  ${JSON.stringify(key)}: ${JSON.stringify(label)},`);
}
lines.push(
  "};",
  "",
  "export function visualizerModuleLoaders(): Record<string, () => Promise<VisualizerType>> {",
  "  return visualizerModules;",
  "}",
  "",
  "export function visualizerModuleNames(): string[] {",
  "  return Object.keys(visualizerModules);",
  "}",
  "",
  "export function visualizerDisplayName(key: string): string | undefined {",
  "  return visualizerDisplayNames[key];",
  "}",
  "",
);

fs.writeFileSync(outFile, lines.join("\n"));
console.log(`wrote ${outFile} (${entries.length} visualizers)`);
